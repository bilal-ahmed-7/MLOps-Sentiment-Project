"""KFP training component supporting the CPU baseline and optional transformer challenger."""
from kfp import dsl


@dsl.component(base_image="sentiment-ml-pipeline:local")
def train_component(
    splits: dsl.Input[dsl.Dataset],
    model_family: str,
    metrics: dsl.Output[dsl.Metrics],
    model_report: dsl.Output[dsl.Artifact],
) -> None:
    """Train a candidate using upstream split data and publish a normalized metrics report."""
    import json
    import shutil
    import subprocess
    import tarfile
    from pathlib import Path

    processed = Path("data/processed")
    shutil.rmtree(processed, ignore_errors=True)
    processed.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(splits.path, "r:gz") as archive:
        archive.extractall("data")  # generated by the preceding trusted pipeline task

    if model_family == "baseline":
        subprocess.run(["python", "-m", "src.models.train"], check=True)
        raw = json.loads(Path("artifacts/metrics.json").read_text(encoding="utf-8"))
        report = {
            "model_family": "baseline", "mlflow_run_id": raw["mlflow_run_id"],
            "val_f1": raw["val_f1"], "test_f1": raw["test_f1"],
            "passed_quality_gate": raw["passed_quality_gate"],
        }
    elif model_family == "huggingface":
        subprocess.run(["python", "-m", "src.models.hf_finetune"], check=True)
        raw = json.loads(Path("artifacts/hf_finetune_report.json").read_text(encoding="utf-8"))
        report = {
            "model_family": "huggingface", "mlflow_run_id": raw["mlflow_run_id"],
            "val_f1": raw["candidate"]["f1"], "test_f1": raw["candidate"]["test_f1"],
            "passed_quality_gate": raw["passed_quality_gate"],
        }
    else:
        raise ValueError("model_family must be 'baseline' or 'huggingface'")

    metrics.log_metric("val_f1", report["val_f1"])
    metrics.log_metric("test_f1", report["test_f1"])
    Path(model_report.path).write_text(json.dumps(report, indent=2), encoding="utf-8")
